/**
 * HEALTHPLEX — official PDF builder (jsPDF + jspdf-autotable v5 functional API).
 *
 * jspdf-autotable v5 does NOT patch jsPDF.prototype; the old side-effect import
 * followed by a prototype call crashes at runtime ("autoTable is not a function").
 * v5 exports a functional `autoTable(doc, opts)` which is what we use. The previous
 * final Y position is exposed on `doc.lastAutoTable.finalY`.
 *
 * Every export carries HEALTHPLEX + GSFC University branding, the selected period,
 * a generated timestamp, and a per-page footer with pagination ("Page i of N").
 */

export type PdfTableOptions = {
  /** Big line under the brand bar, e.g. "Attendance register". */
  title: string;
  /** Small line above the table: period · record counts · generated by. */
  subtitle: string;
  columns: string[];
  rows: (string | number | null | undefined)[][];
  filename: string;
  /** Optional lines printed under the table (e.g. overall summary statistics). */
  summaryLines?: string[];
  /** Optional note shown when rows is empty (defaults to a sensible message). */
  emptyMessage?: string;
  /** Horizontal page size; "landscape" (default) suits wide registers. */
  orientation?: "landscape" | "portrait";
};

const BRAND_NAVY: [number, number, number] = [5, 11, 28];
const BRAND_MINT: [number, number, number] = [79, 224, 162];
const BRAND_INK: [number, number, number] = [232, 238, 249];
const GREY: [number, number, number] = [110, 122, 140];

function istTimestamp(): string {
  return new Date().toLocaleString("en-IN", {
    timeZone: "Asia/Kolkata",
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: true,
  }) + " IST";
}

export async function buildAttendancePdf(opts: PdfTableOptions) {
  const { jsPDF } = await import("jspdf");
  const { autoTable } = await import("jspdf-autotable");

  const orientation = opts.orientation ?? "landscape";
  const doc = new jsPDF({ orientation, unit: "pt", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();

  // ---- brand bar (drawn on every page via didDrawPage for inner pages) ----
  const drawBrandBar = () => {
    doc.setFillColor(...BRAND_NAVY);
    doc.rect(0, 0, pageWidth, 64, "F");
    doc.setFillColor(...BRAND_MINT);
    doc.rect(0, 64, pageWidth, 3, "F");
    doc.setTextColor(...BRAND_MINT);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(16);
    doc.text("HEALTHPLEX", 40, 24);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(...BRAND_INK);
    doc.text("GSFC University · Smart University Gym Management System", 40, 38);
    doc.setTextColor(160, 175, 195);
    doc.setFontSize(7.5);
    doc.text("Official attendance record — for university use", 40, 51);
    doc.setTextColor(...BRAND_INK);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.text(opts.title, pageWidth - 40, 26, { align: "right" });
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7.5);
    doc.setTextColor(160, 175, 195);
    doc.text(`Generated ${istTimestamp()}`, pageWidth - 40, 40, { align: "right" });
  };

  drawBrandBar();

  // ---- subtitle / period line ----
  doc.setTextColor(...GREY);
  doc.setFontSize(8.5);
  const subtitleLines = doc.splitTextToSize(opts.subtitle, pageWidth - 80) as string[];
  doc.text(subtitleLines, 40, 82);
  const tableStartY = 82 + subtitleLines.length * 12 + 6;

  const body = opts.rows.map((r) => r.map((c) => (c == null || c === "" ? "—" : String(c))));

  if (body.length === 0) {
    // empty state — still a valid, branded single-page PDF
    doc.setFillColor(245, 248, 246);
    doc.roundedRect(40, tableStartY + 8, pageWidth - 80, 64, 6, 6, "F");
    doc.setTextColor(90, 105, 130);
    doc.setFontSize(10);
    doc.text(opts.emptyMessage ?? "No records found for the selected period.", 60, tableStartY + 36);
    doc.setFontSize(8);
    doc.text("Adjust the period or filters and export again.", 60, tableStartY + 52);
  } else {
    autoTable(doc, {
      head: [opts.columns],
      body,
      startY: tableStartY,
      styles: { fontSize: 7.4, cellPadding: 4, textColor: [30, 40, 55], lineColor: [225, 232, 228], lineWidth: 0.4 },
      headStyles: { fillColor: [12, 34, 28], textColor: [142, 240, 196], fontStyle: "bold", fontSize: 7.6 },
      alternateRowStyles: { fillColor: [244, 248, 246] },
      margin: { left: 40, right: 40, top: 76, bottom: 44 },
      willDrawPage: (data) => {
        if (data.pageNumber > 1) drawBrandBar();
      },
    });
  }

  // ---- summary lines under the table ----
  if (opts.summaryLines && opts.summaryLines.length) {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const finalY = ((doc as any).lastAutoTable?.finalY as number | undefined) ?? tableStartY + 80;
    let y = Math.min(finalY + 16, pageHeight - 52);
    doc.setDrawColor(207, 220, 212);
    doc.setLineWidth(0.6);
    doc.line(40, y - 6, pageWidth - 40, y - 6);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(18, 52, 38);
    doc.text("SUMMARY", 40, y + 6);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(60, 72, 88);
    let lineY = y + 20;
    for (const line of opts.summaryLines) {
      if (lineY > pageHeight - 34) {
        doc.addPage();
        drawBrandBar();
        lineY = 84;
      }
      doc.text(doc.splitTextToSize(line, pageWidth - 80) as string[], 40, lineY);
      lineY += 12;
    }
  }

  // ---- footer with page numbers on every page (two-pass for reliable N) ----
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setDrawColor(225, 232, 228);
    doc.setLineWidth(0.5);
    doc.line(40, pageHeight - 30, pageWidth - 40, pageHeight - 30);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(7);
    doc.setTextColor(...GREY);
    doc.text(`HEALTHPLEX · GSFC University — generated ${istTimestamp()}`, 40, pageHeight - 18);
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - 40, pageHeight - 18, { align: "right" });
  }

  return doc;
}

export async function exportAttendancePdf(opts: PdfTableOptions) {
  const doc = await buildAttendancePdf(opts);
  doc.save(opts.filename);
}
